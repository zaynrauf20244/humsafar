export function uid(prefix: string) {
  return `${prefix}-${Math.random().toString(36).slice(2, 9)}`;
}

export function normalizePkPhone(raw: string) {
  let d = raw.replace(/\D/g, "");
  if (d.startsWith("92") && d.length === 12) d = "0" + d.slice(2);
  return d;
}

export function isValidPkPhone(raw: string) {
  const d = normalizePkPhone(raw);
  return /^03\d{9}$/.test(d);
}

export function formatPkPhone(raw: string) {
  const d = normalizePkPhone(raw);
  if (d.length !== 11) return `+92 ${d}`;
  return `+92 ${d.slice(1, 4)} ${d.slice(4, 7)} ${d.slice(7)}`;
}

/** Digits only — Pakistani CNIC is 13 digits */
export function normalizeCnic(raw: string) {
  return raw.replace(/\D/g, "").slice(0, 13);
}

export function isValidCnic(raw: string) {
  return /^\d{13}$/.test(normalizeCnic(raw));
}

/** Display as xxxxx-xxxxxxx-x when complete */
export function formatCnic(raw: string) {
  const d = normalizeCnic(raw);
  if (d.length <= 5) return d;
  if (d.length <= 12) return `${d.slice(0, 5)}-${d.slice(5)}`;
  return `${d.slice(0, 5)}-${d.slice(5, 12)}-${d.slice(12)}`;
}
